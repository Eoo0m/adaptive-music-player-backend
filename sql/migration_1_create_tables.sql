CREATE TABLE IF NOT EXISTS tracks (
    id              bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    track_key       text NOT NULL UNIQUE,
    title           text,
    artist          text,
    album           text,
    cover_image_url text,
    isrc            text,
    apple_music_id  text,
    playlist_count  int DEFAULT 0
);

CREATE TABLE IF NOT EXISTS track_vectors_simgcl (
    track_key text PRIMARY KEY REFERENCES tracks(track_key) ON DELETE CASCADE,
    embedding vector(64) NOT NULL
);

CREATE TABLE IF NOT EXISTS track_vectors_clip (
    track_key           text PRIMARY KEY REFERENCES tracks(track_key) ON DELETE CASCADE,
    projected_embedding vector(512) NOT NULL
);

CREATE TABLE IF NOT EXISTS track_vectors_twotower (
    track_key           text PRIMARY KEY REFERENCES tracks(track_key) ON DELETE CASCADE,
    itemtower_embedding vector(128) NOT NULL
);
